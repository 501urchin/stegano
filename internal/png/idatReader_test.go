package png

import (
	"bytes"
	"io"
	"slices"
	"testing"
)

func TestPngDecoder(t *testing.T) {
	tests := []struct {
		name     string
		image    []byte
		expected []byte
		bytes    int
	}{
		{
			name:     "single idat chunk",
			expected: []byte{'h', 'e', 'l', 'l', 'o'},
			bytes:    5,
			image: []byte{
				// PNG signature
				0x89, 0x50, 0x4E, 0x47,
				0x0D, 0x0A, 0x1A, 0x0A,

				// IHDR (fake 1x1)
				0x00, 0x00, 0x00, 0x0D,
				0x49, 0x48, 0x44, 0x52,
				0x00, 0x00, 0x00, 0x01,
				0x00, 0x00, 0x00, 0x01,
				0x08, 0x06,
				0x00, 0x00, 0x00,
				31, 21, 196, 137,

				// IDAT length = 5
				0x00, 0x00, 0x00, 0x05,
				0x49, 0x44, 0x41, 0x54,
				'h', 'e', 'l', 'l', 'o',
				188, 190, 8, 82,

				// IEND
				0x00, 0x00, 0x00, 0x00,
				0x49, 0x45, 0x4E, 0x44,
				0xAE, 0x42, 0x60, 0x82,
			},
		},
		{
			name:     "multiple idat chunks",
			expected: []byte{'h', 'e', 'l', 'l', 'o', ' ', 'w', 'o', 'r', 'l', 'd'},
			bytes:    11,
			image: []byte{
				// PNG signature
				0x89, 0x50, 0x4E, 0x47,
				0x0D, 0x0A, 0x1A, 0x0A,

				// IHDR
				0x00, 0x00, 0x00, 0x0D,
				0x49, 0x48, 0x44, 0x52,
				0x00, 0x00, 0x00, 0x01,
				0x00, 0x00, 0x00, 0x01,
				0x08, 0x06,
				0x00, 0x00, 0x00,
				31, 21, 196, 137,

				// IDAT "hello"
				0x00, 0x00, 0x00, 0x05,
				0x49, 0x44, 0x41, 0x54,
				'h', 'e', 'l', 'l', 'o',
				188, 190, 8, 82,

				// IDAT " world"
				0x00, 0x00, 0x00, 0x06,
				0x49, 0x44, 0x41, 0x54,
				' ', 'w', 'o', 'r', 'l', 'd',
				203, 15, 250, 168,

				// IEND
				0x00, 0x00, 0x00, 0x00,
				0x49, 0x45, 0x4E, 0x44,
				0xAE, 0x42, 0x60, 0x82,
			},
		},
		{
			name:     "boundary crossing",
			expected: []byte{'a', 'b', 'c', 'd', 'e', 'f', 'g'},
			bytes:    7,
			image: []byte{
				// signature
				0x89, 0x50, 0x4E, 0x47, 0x0D, 0x0A, 0x1A, 0x0A,

				// IHDR
				0x00, 0x00, 0x00, 0x0D,
				0x49, 0x48, 0x44, 0x52,
				0x00, 0x00, 0x00, 0x01,
				0x00, 0x00, 0x00, 0x01,
				0x08, 0x06,
				0x00, 0x00, 0x00,
				31, 21, 196, 137,

				// IDAT "abc"
				0, 0, 0, 3,
				'I', 'D', 'A', 'T',
				'a', 'b', 'c',
				51, 175, 214, 114,

				// IDAT "defg"
				0, 0, 0, 4,
				'I', 'D', 'A', 'T',
				'd', 'e', 'f', 'g',
				240, 10, 182, 66,

				// IEND
				0x00, 0x00, 0x00, 0x00,
				0x49, 0x45, 0x4E, 0x44,
				0xAE, 0x42, 0x60, 0x82,
			},
		},
		{
			name:     "ignore non idat chunks",
			expected: []byte{'a', 'b', 'c', 'd', 'e', 'f'},
			bytes:    6,
			image: []byte{
				// PNG signature
				0x89, 0x50, 0x4E, 0x47,
				0x0D, 0x0A, 0x1A, 0x0A,

				// IHDR
				0x00, 0x00, 0x00, 0x0D,
				0x49, 0x48, 0x44, 0x52,
				0x00, 0x00, 0x00, 0x01,
				0x00, 0x00, 0x00, 0x01,
				0x08, 0x06,
				0x00, 0x00, 0x00,
				31, 21, 196, 137,

				// IDAT "abc"
				0x00, 0x00, 0x00, 0x03,
				0x49, 0x44, 0x41, 0x54,
				'a', 'b', 'c',
				51, 175, 214, 114,

				// tEXt "ignored"
				0x00, 0x00, 0x00, 0x07,
				0x74, 0x45, 0x58, 0x74,
				'i', 'g', 'n', 'o', 'r', 'e', 'd',
				247, 199, 190, 77,

				// IDAT "def"
				0x00, 0x00, 0x00, 0x03,
				0x49, 0x44, 0x41, 0x54,
				'd', 'e', 'f',
				10, 79, 118, 209,

				// IEND
				0x00, 0x00, 0x00, 0x00,
				0x49, 0x45, 0x4E, 0x44,
				0xAE, 0x42, 0x60, 0x82,
			},
		},
	}

	for _, test := range tests {
		t.Run(test.name, func(t *testing.T) {
			imageReader := bytes.NewReader(test.image)

			br, err := DecodeChunks(imageReader)
			if err != nil {
				t.Fatal(err)
			}

			_, err = imageReader.Seek(0, io.SeekStart)
			if err != nil {
				t.Fatal(err)
			}

			idatReader, err := NewIdatReader(imageReader, br)
			if err != nil {
				t.Fatal(err)
			}

			result := make([]byte, test.bytes)
			expected := test.expected

			_, err = idatReader.Read(result)
			if err != nil {
				t.Error(err)
			}

			if !slices.Equal(result, expected) {
				t.Errorf("failed to yield expected result. (expected: %q, result: %q)", expected, result)
			}
		})
	}

}
